"""Does WordNet expansion help when the question is NOT phrased like the document?

Why this exists separately from eval_retrieval.py
-------------------------------------------------
The 90 benchmark questions are auto-generated by lifting words verbatim from
the gold passage, so the literal query terms already match. That benchmark is
structurally incapable of showing a benefit from synonym matching, and it duly
reported bm25 and bm25+syn as identical. That is a property of the measuring
instrument, not a result about the feature.

This probe uses questions phrased the way a student would actually ask, which
deliberately avoid the document's own wording - "how many classes do I need to
attend" against a regulation that says "shall put in a minimum of 75% of
attendance".

What this is NOT
----------------
It is not a substitute for the Phase 5 human benchmark. It is a small,
hand-written diagnostic with no gold labels: it reports whether expansion
CHANGES the retrieved set and in which direction, not whether the new set is
more correct. Judging correctness needs gold sources a human assigned. Read it
as "is the mechanism doing anything at all, and is it plausible", then write
the real benchmark.

Circularity warning: do not generate these questions with WordNet. Using the
same lexicon to write the test and to pass it proves nothing. These are typed
by hand.
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

# Hand-written. Each avoids the phrasing the source document is known to use.
QUERIES = [
    "how many classes do I need to attend to sit for exams",
    "what happens if I miss too many lectures",
    "can I get permission if my attendance is low",
    "which rulebook applies to my batch",
    "how are my marks converted into a final score",
    "what do I do if I disagree with my grade",
    "who do I complain to about harassment",
    "what jobs did people get last year and for how much",
    "is there a bus from the city to campus",
    "what money help is available if I cannot pay",
    "which papers do I have to clear to move up a year",
    "what extra specialisation can I take alongside my branch",
    "where do I find the dates for the mid-semester tests",
    "what are the labs and equipment in the CSE department",
]


def fmt(rows):
    return [(r["source_id"], r.get("category"), r.get("page")) for r in rows]


def main():
    from rag.retrieve import Retriever
    r = Retriever()
    print("vocab %d | dense %s\n" % (len(r.bm25.idf), r.dense is not None))

    changed = 0
    promoted = 0
    for q in QUERIES:
        off = r.search(q, "student", topk=5, mode="bm25", expand=False)
        on = r.search(q, "student", topk=5, mode="bm25", expand=True)
        exp = r.last_expansion
        a = [x[0] for x in fmt(off)]
        b = [x[0] for x in fmt(on)]
        new = [x for x in b if x not in a]
        lost = [x for x in a if x not in b]
        if a != b:
            changed += 1
        if new:
            promoted += len(new)

        print("Q: %s" % q)
        print("   expansion: %s" % (exp or "none"))
        if a == b:
            print("   -> identical top-5")
        else:
            print("   -> %d new, %d dropped" % (len(new), len(lost)))
            for sid, cat, pg in fmt(on):
                mark = "NEW " if sid in new else "    "
                print("      %s%-12s p%-4s %s" % (mark, cat, pg, sid[:54]))
        print()

    print("=" * 62)
    print("top-5 changed on %d of %d questions; %d documents promoted"
          % (changed, len(QUERIES), promoted))
    print("This says the mechanism fires. It does NOT say the new documents")
    print("are better - that needs the Phase 5 human benchmark with gold")
    print("sources. Record the judgement, not just the delta.")


if __name__ == "__main__":
    main()
