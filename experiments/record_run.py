"""Materialise the experiment folder experiments/README.md mandates.

    python experiments/record_run.py --run-id 79eca75c --decision SLM-001 \
        --name mistral7b-base --notes "what was being tested"

The README requires, per run:
    <DECISION-ID>__<short-name>__<YYYY-MM-DD>/
        config.yaml    exact parameters, model ids and revisions, hardware
        command.txt    the exact command(s), so the run is reproducible
        results.json   raw measurements, not summaries
        notes.md       what was tested, what surprised you, what to do next

Doing this by hand across eight runs guarantees drift, and a folder that
disagrees with experiments/generation_results.jsonl is worse than no folder.
So the folder is GENERATED from the recorded row: the JSONL stays the single
source of truth and this is a view onto it.
"""
import argparse, json, os, platform, subprocess, sys, time

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RESULTS = os.path.join(ROOT, "experiments", "generation_results.jsonl")


def hardware():
    """Phase 0 gate: 'All benchmarks must be run on this machine, or the
    deviation must be noted in the experiment record.' docs/hardware_profile.md
    still describes the old CPU-only laptop, so record the real machine here
    rather than pointing at a stale document."""
    hw = {"os": platform.platform(), "python": platform.python_version(),
          "cpu": platform.processor()}
    try:
        import torch
        if torch.cuda.is_available():
            p = torch.cuda.get_device_properties(0)
            hw.update(gpu=p.name, vram_gb=round(p.total_memory / 1e9, 1),
                      compute_capability="%d.%d" % (p.major, p.minor),
                      torch=torch.__version__,
                      bf16_supported=torch.cuda.is_bf16_supported())
    except Exception:
        pass
    try:
        hw["nvidia_driver"] = subprocess.check_output(
            ["nvidia-smi", "--query-gpu=driver_version", "--format=csv,noheader"],
            text=True).strip()
    except Exception:
        pass
    return hw


def as_yaml(obj, indent=0):
    """Minimal YAML writer - avoids a pyyaml dependency for a 30-line file."""
    pad = "  " * indent
    out = []
    if isinstance(obj, dict):
        for k, v in obj.items():
            if isinstance(v, (dict, list)) and v:
                out.append("%s%s:" % (pad, k))
                out.append(as_yaml(v, indent + 1))
            else:
                out.append("%s%s: %s" % (pad, k, json.dumps(v)))
    elif isinstance(obj, list):
        for v in obj:
            out.append("%s- %s" % (pad, json.dumps(v)))
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--run-id", required=True)
    ap.add_argument("--decision", required=True, help="e.g. SLM-001 or FT-001")
    ap.add_argument("--name", required=True, help="short-name for the folder")
    ap.add_argument("--command", default=None, help="exact command that produced it")
    ap.add_argument("--notes", default="")
    a = ap.parse_args()

    if not os.path.exists(RESULTS):
        sys.exit("no %s yet - run an evaluation first" % RESULTS)
    row = None
    for line in open(RESULTS, encoding="utf-8"):
        r = json.loads(line)
        if r.get("run_id") == a.run_id:
            row = r
    if row is None:
        sys.exit("run_id %s not found in %s" % (a.run_id, RESULTS))

    date = (row.get("ts") or time.strftime("%Y-%m-%d")).split()[0]
    folder = os.path.join(ROOT, "experiments",
                          "%s__%s__%s" % (a.decision, a.name, date))
    os.makedirs(folder, exist_ok=True)

    cfg = {k: row.get(k) for k in (
        "run_id", "arm", "role", "base_model", "base_revision", "adapter",
        "method", "lora_r", "lora_alpha", "target_modules", "epochs",
        "effective_batch", "max_length", "seed", "infer_quant", "serve_backend",
        "chat_template_variant", "dataset", "dataset_sha256", "max_tokens",
        "temperature", "git_sha")}
    cfg["packages"] = row.get("pkg_versions")
    cfg["hardware"] = hardware()
    with open(os.path.join(folder, "config.yaml"), "w", encoding="utf-8") as f:
        f.write("# Generated by experiments/record_run.py from run_id %s.\n"
                "# Source of truth: experiments/generation_results.jsonl\n"
                % a.run_id)
        f.write(as_yaml(cfg) + "\n")

    with open(os.path.join(folder, "command.txt"), "w", encoding="utf-8") as f:
        f.write((a.command or "(not recorded)") + "\n")

    with open(os.path.join(folder, "results.json"), "w", encoding="utf-8") as f:
        json.dump(row, f, indent=2)

    with open(os.path.join(folder, "notes.md"), "w", encoding="utf-8") as f:
        f.write("# %s - %s\n\n%s\n\n" % (a.decision, a.name, a.notes))
        f.write("## Raw measurements\n\n")
        for k in ("n_requested", "n_ok", "n_failed", "n_f1_items",
                  "n_abstain_items", "grounded_f1", "grounded_f1_ci95",
                  "abstain_recall", "abstain_precision", "false_abstain",
                  "citation_rate", "mean_answer_tokens",
                  "eval_sec_per_answer_gpu", "peak_vram_gb", "train_minutes",
                  "eval_loss_by_epoch"):
            if row.get(k) is not None:
                f.write("- `%s`: %s\n" % (k, row[k]))
        f.write("\nPer-item scores: `%s`\n" % row.get("per_item"))
        f.write("\n## Scope of this number\n\n"
                "Scored on `training/data/test.jsonl` - 147 TEMPLATED held-out\n"
                "examples, split by document group before augmentation. Phase 5\n"
                "(`evaluation/questions.jsonl`) is still empty, so this measures\n"
                "grounded-answering BEHAVIOUR, not real answer quality for real\n"
                "student questions. Same flattering-proxy caveat HANDOFF.md 3.2\n"
                "records for retrieval.\n")
        if row.get("n_failed"):
            f.write("\n**%d request(s) failed** and were excluded from the\n"
                    "denominator. Treat this row with suspicion.\n" % row["n_failed"])

    print("wrote %s" % folder)
    for n in ("config.yaml", "command.txt", "results.json", "notes.md"):
        print("  %s" % n)


if __name__ == "__main__":
    main()
